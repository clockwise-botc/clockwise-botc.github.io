// Builds google-sheets/Code.gs — the one file pasted into Apps Script — from the backend sources plus the
// extension's community and table code, so the Sheet's tidy tabs always match the dashboard's CSV export.
// Run: node scripts/build-backend.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
// Apps Script has no modules: drop import lines and `export` keywords.
const script = (p) => read(p).replace(/^import .*$/gm, '').replace(/^export (const|function|let|class)/gm, '$1');

const parts = [
  ['extension/src/communities.js', script],
  ['extension/src/tables.js', script],
  ['backend/server.js', read],
  ['backend/accounts.js', read],
  ['backend/visibility.js', read],
  ['backend/sheets-store.js', read],
  ['backend/main.js', read],
];

const header = `/**
 * Clockwise shared store — Google Apps Script.
 * Generated by scripts/build-backend.mjs from backend/ and extension/src/; edit those, not this file.
 *
 * Setup (once):
 *   1. Create a Google Sheet. Extensions → Apps Script. Replace everything in Code.gs with this file and save.
 *   2. Project Settings (gear) → Script properties → add three properties:
 *        VIEW_PASSWORD  the password you'll share with your community
 *        WRITE_KEY      the upload key built into the extension
 *        EDITOR_KEY     a key for people allowed to change or delete games
 *   3. Deploy → New deployment → type "Web app". Execute as: Me. Who has access: Anyone. Authorize when asked.
 *   4. Copy the web app URL (ends in /exec).
 * To update later: paste the new file, then Deploy → Manage deployments → edit → Version: New version.
 */
`;

const body = parts.map(([p, load]) => `// ----- ${p} -----\n${load(p).trim()}\n`).join('\n');
const out = path.join(root, 'google-sheets/Code.gs');
fs.writeFileSync(out, `${header}\n${body}`);
console.log(`wrote ${path.relative(root, out)} (${fs.statSync(out).size} bytes)`);
